    // PHP: php.ini + php-fpm pools
    // ------------------------------------------------------------------

    fun writePhpIni(context: Context): File {
        val ini = phpIniAuto(context)
        val tmp = TermuxRuntime.tmpDir(context)
        ini.writeText(
            BANNER +
                "; hardened defaults\n" +
                "expose_php = Off\n" +
                "display_errors = Off\n" +
                "display_startup_errors = Off\n" +
                "log_errors = On\n" +
                "error_reporting = E_ALL & ~E_DEPRECATED & ~E_STRICT\n" +
                "cgi.fix_pathinfo = 0\n" +
                "allow_url_include = Off\n" +
                "allow_url_fopen = Off\n" +
                "enable_dl = Off\n" +
                "session.use_strict_mode = 1\n" +
                "session.cookie_httponly = 1\n" +
                "default_charset = \"UTF-8\"\n" +
                "memory_limit = 256M\n" +
                "upload_max_filesize = 256M\n" +
                "post_max_size = 256M\n" +
                "max_execution_time = 120\n" +
                "max_input_time = 120\n" +
                "output_buffering = 4096\n" +
                "sys_temp_dir = ${tmp.canonicalPath}\n" +
                "upload_tmp_dir = ${tmp.canonicalPath}\n"
        )
        return ini
    }

    /** Pool signature - changes whenever any PHP site config changes. */
    fun phpFpmSignature(sites: List<SiteConfig>): String =
        sites.filter { it.enablePhp }
            .joinToString(";") { "${it.id}:${it.name}:${it.phpExtensions.joinToString(",")}" }

    fun writePhpFpmConf(context: Context, sites: List<SiteConfig>): File {
        val conf = phpFpmConfAuto(context)
        val run = runDir(context)
        val sitesRoot = File(context.filesDir, "sites")
        val sb = StringBuilder(BANNER)
        sb.appendLine("[global]")
        sb.appendLine("pid = ${File(run, "php-fpm.pid").canonicalPath}")
        sb.appendLine("error_log = ${File(logsDir(context), "php-fpm-error.log").canonicalPath}")
        sb.appendLine("daemonize = no")
        sb.appendLine("process_control_timeout = 5s")
        for (site in sites.filter { it.enablePhp }) {
            val customRoot = safeDocRootPath(site.docRoot.trim())
            val docroot = if (customRoot.isEmpty()) File(sitesRoot, site.name) else File(customRoot)
            val sock = siteSocket(context, site.id)
            val siteTmp = File(TermuxRuntime.tmpDir(context), "site-${site.id}").apply { mkdirs() }
            val siteSession = File(siteTmp, "session").apply { mkdirs() }
            sb.appendLine()
            sb.appendLine("[site-${site.id}]")
            sb.appendLine("listen = ${sock.canonicalPath}")
            // Same-uid consumers only (engines run as the app uid); no reason
            // to leave the FastCGI socket world-readable inside run/.
            sb.appendLine("listen.mode = 0660")
            sb.appendLine("pm = dynamic")
            sb.appendLine("pm.max_children = 4")
            sb.appendLine("pm.start_servers = 1")
            sb.appendLine("pm.min_spare_servers = 1")
            sb.appendLine("pm.max_spare_servers = 2")
            sb.appendLine("chdir = /")
            sb.appendLine("catch_workers_output = yes")
            // pool-level directive: FastCGI requests for other extensions are
            // refused outright (core php2shell mitigation)
            sb.appendLine("security.limit_extensions = ${safeTokens(site.phpExtensions).joinToString(" ") { ".$it" }}")
            sb.appendLine("php_admin_value[doc_root] = ${iniQuoted(docroot.canonicalPath)}")
            sb.appendLine("php_admin_value[open_basedir] = ${iniQuoted(docroot.canonicalPath + ":" + siteTmp.canonicalPath)}")
            sb.appendLine("php_admin_value[upload_tmp_dir] = ${iniQuoted(siteTmp.canonicalPath)}")
            sb.appendLine("php_admin_value[sys_temp_dir] = ${iniQuoted(siteTmp.canonicalPath)}")
            sb.appendLine("php_admin_value[session.save_path] = ${iniQuoted(siteSession.canonicalPath)}")
            sb.appendLine("php_admin_value[error_log] = ${iniQuoted(File(logsDir(context), "site-${site.id}-php.log").canonicalPath)}")
            sb.appendLine("php_admin_flag[display_errors] = off")
            sb.appendLine("php_admin_flag[cgi.fix_pathinfo] = 0")
        }
        conf.writeText(sb.toString())
        return conf
    }

