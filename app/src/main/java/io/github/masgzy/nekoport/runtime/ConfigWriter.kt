    // ------------------------------------------------------------------

    /**
     * pure-ftpd command line. NO `-A` here on purpose: chroot(2) needs
     * CAP_SYS_CHROOT which Android untrusted-app uids do not have (pure-ftpd
     * dies with 421 "Unable to set up a secure chroot() jail" right after
     * USER/PASS when built --with-nonroot, verified against pure-ftpd 1.0.54
     * src/ftpd.c). Without -A logins work; the trade-off - FTP users can
     * browse the whole app sandbox - is documented in the UI and README, and
     * the UI refuses account roots that point into sensitive app directories.
     */
    fun pureFtpdArgs(
        context: Context,
        port: Int,
        passiveStart: Int,
        pdbFile: File,
        bind: String = "0.0.0.0",
    ): List<String> = listOf(
        "-4",                          // IPv4 only
        "-S", "$bind,$port",
        "-H",                          // don't resolve host names
        "-f", "none",                  // no syslog on Android
        "-l", "puredb:${pdbFile.canonicalPath}",
        "-p", "$passiveStart:${passiveStart + 32}",
        "-c", "8",                     // max clients
        "-C", "4",                     // max connections per IP
        "-I", "120",                   // idle timeout
        "-U", "022:022",               // umask
        "-b",                          // tolerate broken clients
    )

    fun pureDbFiles(context: Context): Pair<File, File> {
        val run = runDir(context)
        return File(run, "pureftpd.passwd") to File(run, "pureftpd.pdb")
    }

    // ------------------------------------------------------------------
    // MariaDB (MySQL)
    // ------------------------------------------------------------------

    /**
     * Generated MariaDB defaults file. Paths are absolute and live inside the
     * app sandbox; the database listens on localhost only unless the user
     * explicitly allows LAN connections.
     */
    fun writeMariaCnf(context: Context, maria: MariaConfig, datadir: File, localOnly: Boolean = false): File {
        val cnf = mariaCnfAuto(context)
        val prefix = TermuxRuntime.prefixDir(context)
        val run = runDir(context)
        val logs = logsDir(context)
        val tmp = TermuxRuntime.tmpDir(context)
        // settings.localOnly is a global override: it wins over allowRemote.
        val bind = if (localOnly || !maria.allowRemote) "127.0.0.1" else "0.0.0.0"
        cnf.writeText(
            BANNER +
                "[mysqld]\n" +
                "basedir = ${prefix.canonicalPath}\n" +
                "datadir = ${datadir.canonicalPath}\n" +
                "port = ${maria.port}\n" +
                "bind-address = $bind\n" +
                "socket = ${File(run, "mariadb.sock").canonicalPath}\n" +
                "pid-file = ${File(run, "mariadb.pid").canonicalPath}\n" +
                "log-error = ${File(logs, "mariadb.log").canonicalPath}\n" +
                "tmpdir = ${tmp.canonicalPath}\n" +
                "lc-messages-dir = ${File(prefix, "share/mariadb").canonicalPath}\n" +
                "character-sets-dir = ${File(prefix, "share/mariadb/charsets").canonicalPath}\n" +
                "skip-name-resolve\n" +
                "skip-external-locking\n" +
                "default-storage-engine = InnoDB\n" +
                "character-set-server = utf8mb4\n" +
                "collation-server = utf8mb4_general_ci\n" +
                "max_connections = 32\n" +
                "max_allowed_packet = 64M\n" +
                "innodb_buffer_pool_size = 96M\n" +
                "tmp_table_size = 16M\n" +
                "[client]\n" +
                "port = ${maria.port}\n" +
                "socket = ${File(run, "mariadb.sock").canonicalPath}\n"
        )
        return cnf
    }

    /** Database root; kept inside the runtime sandbox (never the web root). */
    fun mariaDataDir(context: Context): File =
        File(TermuxRuntime.runtimeRoot(context), "mariadb/data")
