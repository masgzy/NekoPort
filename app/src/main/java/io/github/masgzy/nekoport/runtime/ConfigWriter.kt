package io.github.masgzy.nekoport.runtime

import android.content.Context
import io.github.masgzy.nekoport.core.Engine
import io.github.masgzy.nekoport.core.MariaConfig
import io.github.masgzy.nekoport.core.SiteConfig
import java.io.File

/**
 * Generates hardened per-site server configurations for the bundled real
 * binaries. All paths are absolute and live inside the app sandbox:
 *
 *  - `runtime/etc/`     generated configs (never served)
 *  - `runtime/logs/`    engine access/error logs (never served)
 *  - `runtime/run/`     pid files + FastCGI unix sockets (never served)
 *  - `sites/<name>/`    document roots (served)
 */
object ConfigWriter {

    private const val BANNER =
        "# Generated by NekoPort - this file is rewritten on every start.\n"

    // ------------------------------------------------------------------
    // Paths
    // ------------------------------------------------------------------

    fun etcDir(context: Context): File = TermuxRuntime.etcDir(context)
    fun runDir(context: Context): File = TermuxRuntime.runDir(context)
    fun logsDir(context: Context): File = TermuxRuntime.logsDir(context)

    fun siteConfDir(context: Context): File = File(etcDir(context), "sites").apply { mkdirs() }

    /** User-editable per-site config; wins over the generated file when present. */
    fun engineConf(context: Context, siteId: Long, engine: Engine): File =
        File(siteConfDir(context), "site-$siteId-${engine.id}.conf")

    /** Regenerated default per-site config (`.auto`). */
    fun engineConfAuto(context: Context, siteId: Long, engine: Engine): File =
        File(siteConfDir(context), "site-$siteId-${engine.id}.conf.auto")

    /** User-editable php-fpm pool config (used instead of the `.auto` when present). */
    fun phpFpmConf(context: Context): File = File(etcDir(context), "php-fpm.conf")
    fun phpFpmConfAuto(context: Context): File = File(etcDir(context), "php-fpm.conf.auto")

    /** php.ini lives at the exact name PHP looks up inside PHPRC. */
    fun phpIni(context: Context): File = File(etcDir(context), "php.ini")
    fun phpIniAuto(context: Context): File = File(etcDir(context), "php.ini.auto")

    /** MariaDB defaults file (user-editable) and its generated twin. */
    fun mariaCnf(context: Context): File = File(mariaConfDir(context), "my.cnf")
    fun mariaCnfAuto(context: Context): File = File(mariaConfDir(context), "my.cnf.auto")
    fun mariaConfDir(context: Context): File = File(etcDir(context), "mariadb").apply { mkdirs() }

    /** Cron scheduler log. */
    fun cronLog(context: Context): File = File(logsDir(context), "cron.log")

    fun siteSocket(context: Context, siteId: Long): File = File(runDir(context), "php-$siteId.sock")
    fun siteErrorLog(context: Context, siteId: Long, engine: Engine): File =
        File(logsDir(context), "site-$siteId-${engine.id}-error.log")
    fun siteAccessLog(context: Context, siteId: Long, engine: Engine): File =
        File(logsDir(context), "site-$siteId-${engine.id}-access.log")

    /** The config file a server actually consumes: the user file when present, else the `.auto`.
     *  Guard rail: a Termux path leak in the user copy (pasted from Termux, restored backup)
     *  is regex-rewritten to the NekoPort equivalent before the server sees it. */
    fun effectiveConf(context: Context, auto: File): File {
        val user = File(auto.parentFile, auto.name.removeSuffix(".auto"))
        val chosen = if (user.exists()) user else auto
        runCatching {
            val prefix = TermuxRuntime.prefixDir(context)
            val root = TermuxRuntime.runtimeRoot(context)
            PathGuard.sanitizeAndVerify(chosen, prefix.canonicalPath, root.canonicalPath)
        }
        return chosen
    }

    /** Seeds the user-editable file from the generated one (no-op when it already exists). */
    fun ensureUserCopy(auto: File): File {
        val user = File(auto.parentFile, auto.name.removeSuffix(".auto"))
        if (!user.exists() && auto.exists()) {
            runCatching { auto.copyTo(user, overwrite = true) }
        }
        return user
    }

    /** Deletes the user file so the generated `.auto` takes over again. */
    fun resetToAuto(auto: File): Boolean {
        val user = File(auto.parentFile, auto.name.removeSuffix(".auto"))
        return if (user.exists()) user.delete() else false
    }

    private fun quoted(path: File) = "\"" + path.canonicalPath + "\""

    /**
     * php-fpm ini values: quote AND escape. Bare values are truncated at the
     * first space (`/sdcard/My Documents` became `/sdcard/My`, silently
     * breaking open_basedir), and a raw newline inside the user-typed docRoot
     * injected arbitrary pool directives - e.g. clearing
     * security.limit_extensions (php2shell protection) or widening
     * open_basedir to /. Quotes are escaped so the value stays one line.
     */
    private fun iniQuoted(path: String): String {
        val clean = path.replace("\r", " ").replace("\n", " ").replace("\\", "\\\\").replace("\"", "\\\"")
        return "\"$clean\""
    }

    /**
     * Last-resort sanitization for a STORED docRoot: the UI now validates
     * docRoot on save, but legacy configs (or hand-edited config.json) may
     * still carry quotes/newlines that break out of the quoted engine
     * directives (nginx root, Apache <Directory>, php-fpm pool values).
     */
    fun safeDocRootPath(path: String): String =
        path.replace("\r", " ").replace("\n", " ").replace("\"", "")

    /**
     * Config tokens (index file names, PHP extensions, deny-dir names) are
     * user-typed and get spliced into nginx/Apache/lighttpd/php-fpm config
     * text. Anything outside [A-Za-z0-9._-] can smuggle quotes/backslashes
     * into the generated file and break the server at parse time with an
     * unreadable error - filter strictly instead.
     */
    private fun safeTokens(raw: List<String>): List<String> =
        raw.map { it.filter { c -> c.isLetterOrDigit() || c in "._-" } }
            .filter { it.isNotEmpty() }
            .distinct()

    /** Regenerates the `.auto` config of [site]'s engine (used before editing). */
    fun writeEngineConf(context: Context, site: SiteConfig, docroot: File, localOnly: Boolean = false): File = when (site.engine) {
        Engine.NGINX -> writeNginxConf(context, site, docroot, localOnly)
        Engine.APACHE -> writeHttpdConf(context, site, docroot, localOnly)
        Engine.LIGHTTPD -> writeLighttpdConf(context, site, docroot, localOnly)
    }

    /** nginx's `index` directive takes SPACE-separated file names; a comma is
     *  a parse error ("unexpected ,") that killed every nginx site (the
     *  lighttpd tuple syntax is the only place where commas are valid). */
    private fun nginxIndexList(site: SiteConfig): String {
        val tokens = safeTokens(site.indexFiles).ifEmpty { listOf("index.html") }
        return tokens.joinToString(" ") { "\"$it\"" }
    }

    /** DirectoryIndex / index-file.names fall back to index.html when the
     *  cleaned token list is empty, so the generated line stays valid. */
    private fun indexTokens(site: SiteConfig): List<String> =
        safeTokens(site.indexFiles).ifEmpty { listOf("index.html") }

    private fun phpExtensions(site: SiteConfig) =
        safeTokens(site.phpExtensions).joinToString("|") { Regex.escape(it) }

    // ------------------------------------------------------------------
    // nginx
    // ------------------------------------------------------------------

    fun writeNginxConf(context: Context, site: SiteConfig, docroot: File, localOnly: Boolean = false): File {
        val prefix = TermuxRuntime.prefixDir(context)
        val run = runDir(context)
        val sock = siteSocket(context, site.id)
        val conf = engineConfAuto(context, site.id, Engine.NGINX)
        val ext = phpExtensions(site)
        val php = if (site.enablePhp) {
            "\n" +
                "    location ~* \\.(${ext})\$ {\n" +
                "        fastcgi_pass unix:${sock.canonicalPath};\n" +
                "        fastcgi_index index.php;\n" +
                "        include ${File(prefix, "etc/nginx/fastcgi.conf").canonicalPath};\n" +
                "        fastcgi_param PATH_INFO \"\";\n" +
                "    }\n"
        } else ""

        // PHP execution is refused inside upload directories (webshell protection).
        val denyDirs = safeTokens(site.phpDenyDirs).joinToString("|") { Regex.escape(it) }
        val denyBlock = if (denyDirs.isNotEmpty()) {
            "\n" +
                "        # PHP execution refused in upload directories\n" +
                "        location ~* ^/(?:$denyDirs)(?:/|\$) {\n" +
                (if (site.enablePhp) "            location ~* \\.(${ext})\$ { return 403; }\n"
                 else "") +
                "            try_files \$uri \$uri/ =404;\n" +
                "        }\n"
        } else ""

        conf.writeText(
            BANNER +
                "daemon off;\n" +
                "worker_processes 1;\n" +
                "pid ${File(run, "nginx-${site.id}.pid").canonicalPath};\n" +
                "error_log ${quoted(siteErrorLog(context, site.id, Engine.NGINX))} warn;\n" +
                "events {\n    worker_connections 256;\n}\n" +
                "http {\n" +
                "    include ${File(prefix, "etc/nginx/mime.types").canonicalPath};\n" +
                "    default_type application/octet-stream;\n" +
                "    sendfile on;\n" +
                "    tcp_nopush on;\n" +
                "    keepalive_timeout 65;\n" +
                "    client_max_body_size 512m;\n" +
                "    server_tokens off;\n" +
                "    access_log ${quoted(siteAccessLog(context, site.id, Engine.NGINX))};\n" +
                // The binary is a Termux build with its temp dirs compiled in
                // as /data/data/com.termux/... (never writable from this app:
                // mkdir() failed 13: Permission denied and nginx exited with
                // [emerg] before opening any port). Override ALL of them -
                // only the client_body one is actually used for static sites,
                // but a stray proxy/fastcgi buffer would hit the same wall.
                nginxTempPaths(run) +
                "    server {\n" +
                "        listen ${if (localOnly) "127.0.0.1:" else ""}${site.port};\n" +
                "        server_name _;\n" +
                "        root ${quoted(docroot)};\n" +
                "        index ${nginxIndexList(site)};\n" +
                "        autoindex ${if (site.directoryListing) "on" else "off"};\n" +
                "\n" +
                "        # never serve dotfiles (.htaccess, .git, .env, ...)\n" +
                "        location ~ /\\. {\n" +
                "            deny all;\n" +
                "        }\n" +
                "\n" +
                "        location / {\n" +
                "            try_files \$uri \$uri/ =404;\n" +
                "        }\n" +
                denyBlock +
                php +
                "    }\n" +
                "}\n"
        )
        return conf
    }

    // ------------------------------------------------------------------
    // Apache httpd
    // ------------------------------------------------------------------

    private fun apacheModule(name: String, prefix: File) =
        "LoadModule $name ${File(File(prefix, "libexec/apache2"), "mod_" + name.removeSuffix("_module") + ".so").canonicalPath}\n"

    /** Loopback bind when [localOnly], else all interfaces (previous behavior). */
    private fun bindHost(localOnly: Boolean) = if (localOnly) "127.0.0.1" else "0.0.0.0"

    /** Explicit nginx temp dirs inside the app sandbox. nginx only creates
     *  the LAST path component itself; the parent must exist. */
    private fun nginxTempPaths(run: File): String {
        val dirs = listOf("client_body", "proxy", "fastcgi", "uwsgi", "scgi")
        val sb = StringBuilder()
        for (name in dirs) {
            val dir = File(File(run, "nginx-tmp"), name)
            runCatching { dir.mkdirs() }
            sb.append("    ${name}_temp_path ${quoted(dir)};\n")
        }
        return sb.toString()
    }

    fun writeHttpdConf(context: Context, site: SiteConfig, docroot: File, localOnly: Boolean = false): File {
        val prefix = TermuxRuntime.prefixDir(context)
        val run = runDir(context)
        // DefaultRuntimeDir/Mutex point here; httpd does NOT create it itself
        // (AH00140: Could not create scoreboard) so it must pre-exist.
        runCatching { File(run, "apache").mkdirs() }
        val conf = engineConfAuto(context, site.id, Engine.APACHE)
        val sock = siteSocket(context, site.id)
        val ext = phpExtensions(site)
        val modules = listOf(
            "mpm_worker_module", "authz_core_module", "authz_host_module",
            "unixd_module", "log_config_module", "mime_module", "dir_module",
            "autoindex_module", "headers_module", "setenvif_module",
            "filter_module", "reqtimeout_module", "proxy_module", "proxy_fcgi_module",
            "rewrite_module",
        )
        val phpLine = if (site.enablePhp) {
            val escapedDocroot = docroot.canonicalPath
            "\n" +
                "    # PHP via FastCGI (php-fpm) - source code of unknown extensions is\n" +
                "    # served as plain text and never executed (php2shell mitigation).\n" +
                "    ProxyPassMatch \"^/(.+(?:\\.(?:${ext}))\$)\" \"unix:${sock.canonicalPath}|fcgi://localhost${escapedDocroot}/\$1\"\n"
        } else ""

        // PHP execution is refused inside upload directories (webshell protection).
        val denyDirs = safeTokens(site.phpDenyDirs).joinToString("|") { Regex.escape(it) }
        // DirectoryMatch is a REGEX: a docroot like /sdcard/www.test.com would
        // widen the match ("." = any char) and a path with ( or + made the
        // whole config illegal. \Q...\E (PCRE) quotes the docroot literally.
        val denyBlock = if (denyDirs.isNotEmpty() && site.enablePhp) {
            "\n" +
                "<DirectoryMatch \"^${Regex.escape(docroot.canonicalPath)}/(?:$denyDirs)(?:/|\$)\">\n" +
                "    <FilesMatch \"\\.(?:${ext})\$\">\n" +
                "        Require all denied\n" +
                "    </FilesMatch>\n" +
                "</DirectoryMatch>\n"
        } else ""

        conf.writeText(
            BANNER +
                modules.joinToString("") { apacheModule(it, prefix) } +
                "\n" +
                "ServerRoot ${quoted(TermuxRuntime.runtimeRoot(context))}\n" +
                // The Termux httpd build has its runtime dir compiled in as
                // /data/data/com.termux/.../var/run/apache2; without this
                // override the parent process aborted before writing any
                // stderr output (errors only landed in the site ErrorLog),
                // surfacing as a bare "did not open port; no launch output".
                // Same for the default mutex location.
                "DefaultRuntimeDir ${quoted(File(run, "apache"))}\n" +
                "Mutex file:${quoted(File(run, "apache"))} default\n" +
                "ServerName localhost\n" +
                "PidFile ${quoted(File(run, "apache-${site.id}.pid"))}\n" +
                "Listen ${if (localOnly) "127.0.0.1:" else ""}${site.port}\n" +
                "\n" +
                "ErrorLog ${quoted(siteErrorLog(context, site.id, Engine.APACHE))}\n" +
                "LogLevel warn\n" +
                "LogFormat \"%h %l %u %t \\\"%r\\\" %>s %b \\\"%{Referer}i\\\" \\\"%{User-Agent}i\\\"\" combined\n" +
                "CustomLog ${quoted(siteAccessLog(context, site.id, Engine.APACHE))} combined\n" +
                "\n" +
                "TypesConfig ${quoted(File(File(prefix, "etc/apache2"), "mime.types"))}\n" +
                "DirectoryIndex ${indexTokens(site).joinToString(" ")}\n" +
                "Timeout 300\n" +
                "KeepAlive On\n" +
                "KeepAliveTimeout 5\n" +
                "MaxKeepAliveRequests 200\n" +
                "\n" +
                "# phone-friendly worker limits\n" +
                "<IfModule mpm_worker_module>\n" +
                "    ServerLimit 4\n" +
                "    ThreadsPerChild 8\n" +
                "    MinSpareThreads 4\n" +
                "    MaxSpareThreads 16\n" +
                "    MaxRequestWorkers 32\n" +
                "</IfModule>\n" +
                "\n" +
                "ServerTokens Prod\n" +
                "ServerSignature Off\n" +
                "TraceEnable Off\n" +
                "Options -Indexes\n" +
                (if (site.directoryListing) "\n<Directory \"${docroot.canonicalPath}\">\n" +
                    "    Options +Indexes\n" +
                    "</Directory>\n" else "") +
                "\n" +
                "<Directory />\n" +
                "    AllowOverride None\n" +
                "    Require all denied\n" +
                "</Directory>\n" +
                "\n" +
                "<Directory \"${docroot.canonicalPath}\">\n" +
                "    AllowOverride None\n" +
                "    Require all granted\n" +
                "</Directory>\n" +
                "\n" +
                "<FilesMatch \"^\\.\">\n" +
                "    Require all denied\n" +
                "</FilesMatch>\n" +
                phpLine +
                denyBlock
        )
        return conf
    }

    // ------------------------------------------------------------------
    // lighttpd
    // ------------------------------------------------------------------

    fun writeLighttpdConf(context: Context, site: SiteConfig, docroot: File, localOnly: Boolean = false): File {
        val run = runDir(context)
        val conf = engineConfAuto(context, site.id, Engine.LIGHTTPD)
        val sock = siteSocket(context, site.id)
        val ext = phpExtensions(site)
        val php = if (site.enablePhp) {
            val hosts = safeTokens(site.phpExtensions).joinToString(",\n") { extName ->
                "    \".${Regex.escape(extName)}\" => ((\"socket\" => \"${sock.canonicalPath}\"))"
            }
            "\nfastcgi.server = (\n$hosts\n)\n"
        } else ""

        // PHP execution is refused inside upload directories (webshell protection).
        val denyDirs = safeTokens(site.phpDenyDirs).joinToString("|") { Regex.escape(it) }
        val denyBlock = if (denyDirs.isNotEmpty() && site.enablePhp) {
            """
            |${'$'}HTTP["url"] =~ "^/(?:$denyDirs)(?:/|${'$'})" {
            |    ${'$'}HTTP["url"] =~ "\.(?:$ext)${'$'}" {
            |        url.access-deny = ( "" )
            |    }
            |}
            """.trimMargin()
        } else ""

        conf.writeText(
            BANNER +
                "server.modules = (\"mod_accesslog\")\n" +
                "\n" +
                "server.port = ${site.port}\n" +
                "server.bind = \"${bindHost(localOnly)}\"\n" +
                "server.document-root = ${quoted(docroot)}\n" +
                "server.errorlog = ${quoted(siteErrorLog(context, site.id, Engine.LIGHTTPD))}\n" +
                "accesslog.filename = ${quoted(siteAccessLog(context, site.id, Engine.LIGHTTPD))}\n" +
                "server.pid-file = ${quoted(File(run, "lighttpd-${site.id}.pid"))}\n" +
                "server.upload-dirs = ( ${quoted(TermuxRuntime.tmpDir(context))} )\n" +
                "\n" +
                "index-file.names = ( ${indexTokens(site).joinToString(", ") { "\"$it\"" }} )\n" +
                "server.dir-listing = \"${if (site.directoryListing) "enable" else "disable"}\"\n" +
                "\n" +
                "mimetype.assign = (\n" +
                "    \".html\" => \"text/html\",  \".htm\" => \"text/html\",\n" +
                "    \".css\" => \"text/css\",    \".js\" => \"text/javascript\",\n" +
                "    \".json\" => \"application/json\", \".xml\" => \"text/xml\",\n" +
                "    \".png\" => \"image/png\",   \".jpg\" => \"image/jpeg\", \".jpeg\" => \"image/jpeg\",\n" +
                "    \".gif\" => \"image/gif\",   \".svg\" => \"image/svg+xml\", \".ico\" => \"image/x-icon\",\n" +
                "    \".webp\" => \"image/webp\", \".txt\" => \"text/plain\", \".pdf\" => \"application/pdf\",\n" +
                "    \".zip\" => \"application/zip\", \".mp3\" => \"audio/mpeg\", \".mp4\" => \"video/mp4\",\n" +
                "    \".woff\" => \"font/woff\",  \".woff2\" => \"font/woff2\"\n" +
                ")\n" +
                "\n" +
                "# never serve dotfiles\n" +
                "\$HTTP[\"url\"] =~ \"/\\\\.\" {\n" +
                "    url.access-deny = ( \"\" )\n" +
                "}\n" +
                denyBlock +
                php
        )
        return conf
    }

